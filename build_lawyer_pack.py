def para(d, text, bold=False, size=12, italic=False):
    p = d.add_paragraph()
    r = p.add_run(text)
    r.bold, r.italic = bold, italic
    r.font.name, r.font.size = "Times New Roman", Pt(size)
    p.paragraph_format.space_after = Pt(4)
    return p


def page_break(d):
    d.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


def append_docx(d, data: bytes):
    src = Document(io.BytesIO(data))
    for el in src.element.body:
        if el.tag.endswith("}sectPr"):
            continue
        d.element.body.sectPr.addprevious(copy.deepcopy(el))


def samples(cat, doc_id):
    doc = cat.docs[doc_id]
    for ov in test_all.VARIANTS.get(doc_id, [{}]):
        answers = {}
        while True:
            q = engine.next_question(doc, answers, test_all.CFG)
            if q is None:
                break
            answers[q["key"]] = test_all.example_value(q, ov)
        if any(w["block"] for w in engine.check_warnings(doc, answers, test_all.CFG)):
            continue
        yield engine.render_text(doc, answers, test_all.CFG)


